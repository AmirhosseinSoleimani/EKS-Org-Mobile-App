import 'package:eks_sana_plus_org/src/features/emdad_unit/domain/entities/emdad_unit_entity.dart';

class EmdadUnitModel extends EmdadUnitEntity {
  const EmdadUnitModel({
    super.id,
    super.agencyInfoId,
    super.parentId,
    super.type,
    super.grade,
    super.typeTitle,
    super.name,
    super.agencyPersonId,
    super.agencyVehicleId,
    super.vehicleInfoId,
    super.agencyInfoName,
    super.vehicleInfoTitle,
    super.personInfoFullName,
    super.imageBase64,
    super.seatType,
    super.seatTypeTitle,
    super.score,
    super.latitude,
    super.longitude,
    super.locationId,
    super.locationTitle,
    super.address,
    super.imageGuid,
    super.isActive,
    super.gradeTitle,
    super.gradePatternName,
    super.gradePatternCode,
    super.gradeCoefficient,
    super.managmentCommisionPercent,
    super.insertUserFullName,
    super.updateUserFullName,
    super.insertDateTimeJalali,
    super.updateDateTimeJalali,
  });

  factory EmdadUnitModel.fromJson(Map<String, dynamic> json) {
    return EmdadUnitModel(
      id: json['id'] as int?,
      agencyInfoId: json['agencyInfoId'] as int?,
      parentId: json['parentId'] as int?,
      type: json['type'] as int?,
      grade: json['grade'] as int?,
      typeTitle: json['typeTitle'] as String?,
      name: json['name'] as String?,
      agencyPersonId: json['agencyPersonId'] as int?,
      agencyVehicleId: json['agencyVehicleId'] as int?,
      vehicleInfoId: json['vehicleInfoId'] as int?,
      agencyInfoName: json['agencyInfoName'] as String?,
      vehicleInfoTitle: json['vehicleInfoTitle'] as String?,
      personInfoFullName: json['personInfoFullName'] as String?,
      imageBase64: json['imageBase64'] as String?,
      seatType: json['seatType'] as int?,
      seatTypeTitle: json['seatTypeTitle'] as String?,
      score: json['score'] as int?,
      latitude: (json['latitude'] as num?)?.toDouble(),
      longitude: (json['longitude'] as num?)?.toDouble(),
      locationId: json['locationId'] as int?,
      locationTitle: json['locationTitle'] as String?,
      address: json['address'] as String?,
      imageGuid: json['imageGuid'] as String? ?? json['imageGuie'] as String?,
      isActive: json['isActive'] as bool?,
      gradeTitle: json['gradeTitle'] as String?,
      gradePatternName: json['gradePatternName'] as String?,
      gradePatternCode: json['gradePatternCode'] as int?,
      gradeCoefficient: json['gradeCoefficient'] as num?,
      managmentCommisionPercent: json['managmentCommisionPercent'] as num?,
      insertUserFullName: json['insertUserFullName'] as String?,
      updateUserFullName: json['updateUserFullName'] as String?,
      insertDateTimeJalali: json['insertDateTimeJalali'] as String?,
      updateDateTimeJalali: json['updateDateTimeJalali'] as String?,
    );
  }
}
