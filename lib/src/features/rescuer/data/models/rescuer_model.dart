import 'package:eks_sana_plus_org/src/features/rescuer/domain/entities/rescuer_entity.dart';

class RescuerModel extends RescuerEntity {
  const RescuerModel({
    super.id,
    super.code,
    super.firstName,
    super.lastName,
    super.nationalNumber,
    super.birthDate,
    super.birthDateJalali,
    super.fatherName,
    super.cityIdPlaceOfBirth,
    super.cityNamePlaceOfBirth,
    super.provinceNamePlaceOfBirth,
    super.cityIdIssuingPlace,
    super.cityNameIssuingPlace,
    super.provinceNameIssuingPlace,
    super.degree,
    super.degreeTitle,
    super.marital,
    super.maritalTitle,
    super.tel,
    super.mobile,
    super.insertUserFullName,
    super.updateUserFullName,
    super.insertDateTime,
    super.insertDateTimeJalali,
    super.updateDateTime,
    super.updateDateTimeJalali,
    super.cityIdAddress,
    super.address,
    super.status,
    super.statusTitle,
    super.licenseCode,
    super.imageGuid,
    super.imageBase64,
    super.isCreateUserInfo,
    super.shoesSize,
    super.clothingSize,
    super.certificatesTitle,
    super.isActive,
    super.isDeleted,
    super.reportFields,
  });

  factory RescuerModel.fromJson(Map<String, dynamic> json) {
    return RescuerModel(
      id: (json['id'] as num?)?.toInt(),
      code: json['code']?.toString(),
      firstName: json['firstName']?.toString(),
      lastName: json['lastName']?.toString(),
      nationalNumber: json['nationalNumber']?.toString(),
      birthDate: json['birthDate']?.toString(),
      birthDateJalali: json['birthDateJalali']?.toString(),
      fatherName: json['fatherName']?.toString(),
      cityIdPlaceOfBirth: (json['cityIdPlaceOfBirth'] as num?)?.toInt(),
      cityNamePlaceOfBirth: json['cityNamePlaceOfBirth']?.toString(),
      provinceNamePlaceOfBirth:
          json['provinceNamePlaceOfBirth']?.toString(),
      cityIdIssuingPlace: (json['cityIdIssuingPlace'] as num?)?.toInt(),
      cityNameIssuingPlace: json['cityNameIssuingPlace']?.toString(),
      provinceNameIssuingPlace:
          json['provinceNameIssuingPlace']?.toString(),
      degree: (json['degree'] as num?)?.toInt(),
      degreeTitle: json['degreeTitle']?.toString(),
      marital: (json['marital'] as num?)?.toInt(),
      maritalTitle: json['maritalTitle']?.toString(),
      tel: json['tel']?.toString(),
      mobile: json['mobile']?.toString(),
      insertUserFullName: json['insertUserFullName']?.toString(),
      updateUserFullName: json['updateUserFullName']?.toString(),
      insertDateTime: json['insertDateTime']?.toString(),
      insertDateTimeJalali: json['insertDateTimeJalali']?.toString(),
      updateDateTime: json['updateDateTime']?.toString(),
      updateDateTimeJalali: json['updateDateTimeJalali']?.toString(),
      cityIdAddress: (json['cityIdAddress'] as num?)?.toInt(),
      address: json['address']?.toString(),
      status: (json['status'] as num?)?.toInt(),
      statusTitle: json['statusTitle']?.toString(),
      licenseCode: json['licenseCode']?.toString(),
      imageGuid: json['imageGuid']?.toString(),
      imageBase64: json['imageBase64']?.toString(),
      isCreateUserInfo: json['isCreateUserInfo'] as bool?,
      shoesSize: (json['shoesSize'] as num?)?.toInt(),
      clothingSize: json['clothingSize']?.toString(),
      certificatesTitle: json['certificatesTitle']?.toString(),
      isActive: json['isActive'] as bool?,
      isDeleted: json['isDeleted'] as bool?,
      reportFields: Map<String, dynamic>.unmodifiable(json),
    );
  }
}
