import 'package:eks_sana_plus_org/src/features/services/domain/entities/subscription_info_entity.dart';

class SubscriptionInfoModel extends SubscriptionInfoEntity {
  SubscriptionInfoModel({
    super.carModelId,
    super.productId,
    super.code,
    super.carName,
    super.productionYear,
    super.licensePlateNo,
    super.chassisNo,
    super.vin,
    super.colorId,
    super.engineNumber,
    super.nationalCode,
    super.firstName,
    super.lastName,
    super.address,
    super.mobileNumber,
    super.discountId,
    super.fromDate,
    super.toDate,
    super.saleProductId,
    super.saleProductTitle,
    super.fromKilometer,
    super.toKilometer,
    super.agencyCode,
    super.authorType,
    super.isDeleted,
    super.productTitle,
    super.productServiceType,
    super.productRequiredSubscription,
    super.isInverse,
    super.inverseText,
    super.inverseDateTime,
    super.isNullification,
    super.nullificationText,
    super.nullificationDateTime,
    super.factorNo,
    super.checkStatusBasedDateTime,
    super.emdadPackageId,
    super.emdadPackageCode,
    super.emdadServiceId,
    super.emdadServiceCode,
    super.description,
    super.isActive,
    super.isActiveTitle,
    super.status,
    super.statusTitle,
  });

  factory SubscriptionInfoModel.fromJson(Map<String, dynamic> json) {
    return SubscriptionInfoModel(
      carModelId: json['carModelId'],
      productId: json['productId'],
      code: json['code'],
      carName: json['carName'],
      productionYear: json['productionYear'],
      licensePlateNo: json['licensePlateNo'],
      chassisNo: json['chassisNo'],
      vin: json['vin'] ?? json['VIN'],
      colorId: json['colorId'],
      engineNumber: json['engineNumber'],
      nationalCode: json['nationalCode'],
      firstName: json['firstName'],
      lastName: json['lastName'],
      address: json['address'],
      mobileNumber: json['mobileNumber'],
      discountId: json['discountId'],
      fromDate: _dateTime(json['fromDate']),
      toDate: _dateTime(json['toDate']),
      saleProductId: json['saleProductId'],
      saleProductTitle: json['saleProductTitle'],
      fromKilometer: json['fromKilometer'],
      toKilometer: json['toKilometer'],
      agencyCode: json['agencyCode'],
      authorType: json['authorType'],
      isDeleted: json['isDeleted'] ?? false,
      productTitle: json['productTitle'],
      productServiceType: json['productServiceType'],
      productRequiredSubscription: json['productRequiredSubscription'],
      isInverse: json['isInverse'] ?? false,
      inverseText: json['inverseText'],
      inverseDateTime: _dateTime(json['inverseDateTime']),
      isNullification: json['isNullification'] ?? false,
      nullificationText: json['nullificationText'],
      nullificationDateTime: _dateTime(json['nullificationDateTime']),
      factorNo: json['factorNo'],
      checkStatusBasedDateTime: _dateTime(json['checkStatusBasedDateTime']) ?? DateTime.now(),
      emdadPackageId: json['emdadPackageId'],
      emdadPackageCode: json['emdadPackageCode'],
      emdadServiceId: json['emdadServiceId'],
      emdadServiceCode: json['emdadServiceCode'],
      description: json['description'],
      isActive: json['isActive'],
      isActiveTitle: json['isActiveTitle'],
      status: json['status'],
      statusTitle: json['statusTitle'],
    );
  }

  static DateTime? _dateTime(dynamic value) {
    if (value == null) return null;
    return DateTime.tryParse(value.toString());
  }
}