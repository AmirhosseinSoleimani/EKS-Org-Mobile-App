    super.endDateText,
    super.shiftTypeText,
    super.shiftTypeId,
    super.planningId,
    super.imeiId,
    super.khodroAgnecyId,
    super.shiftId,
    super.tarhId,
    super.nStatus,
    super.nVisible,
    super.nPlanType,
    super.tarhNameText,
    super.tarhCode,
    super.nImei,
    super.shiftCode,
    super.shiftName,
    super.plakKhodroTypeText,
    super.mahalCode,
    super.mahalNameText,
    super.agencyCode,
    super.aidPerCodeId,
    super.agencyName,
    super.aidPerName1,
    super.plakText,
    super.khodroTypeText,
