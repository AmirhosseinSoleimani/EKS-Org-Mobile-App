  factory EmdadgarModel.fromJson(Map<String, dynamic> json) {
    return EmdadgarModel(
      id: json["id"],
      startDateText: json["startDateText"],
      endDateText: json["endDateText"],
      shiftTypeText: json["shiftTypeText"],
      shiftTypeId: json["shiftTypeId"],
      planningId: json["planningId"],
      imeiId: json["imeiId"],
      khodroAgnecyId: json["khodroAgnecyId"],
      shiftId: json["shiftId"],
      tarhId: json["tarhId"],
      nStatus: json["nStatus"],
      nVisible: json["nVisible"],
