      tarhCode: json["tarhCode"],
      nImei: json["nImei"],
      shiftCode: json["shiftCode"],
      shiftName: json["shiftName"],
      plakKhodroTypeText: json["plakKhodroTypeText"],
      mahalCode: json["mahalCode"],
      mahalNameText: json["mahalNameText"],
      agencyCode: json["agencyCode"],
      aidPerCodeId: json["aidPerCodeId"],
      agencyName: json["agencyName"],
      aidPerName1: json["aidPerName1"],
