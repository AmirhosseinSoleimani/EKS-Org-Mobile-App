import 'package:eks_sana_plus_org/src/features/agency_info/data/models/agency_info_json_helper.dart';
import 'package:eks_sana_plus_org/src/features/agency_info/data/models/agency_vehicle_grade_detail_model.dart';
import 'package:eks_sana_plus_org/src/features/agency_info/domain/entities/agency_vehicle_entity.dart';

class AgencyVehicleModel extends AgencyVehicleEntity {
  const AgencyVehicleModel({
    super.id,
    super.agencyInfoId,
    super.vehicleInfoId,
    super.vehicleModelName,
    super.vehicleModelTitle,
    super.navganTypeTitle,
    super.imei,
    super.imeiSerial,
    super.navganTypeCode,
    super.contractStartDate,
    super.contractStartDateJalali,
    super.contractEndDate,
    super.contractEndDateJalali,
    super.startBimeDate,
    super.startBimeDateJalali,
    super.endBimeDate,
    super.endBimeDateJalali,
    super.status,
    super.statusTitle,
    super.contractCode,
    super.contractType,
    super.contractTypeTitle,
    super.labelAgencyCode,
    super.insertUserFullName,
    super.updateUserFullName,
    super.insertDateTime,
    super.insertDateTimeJalali,
    super.updateDateTime,
    super.updateDateTimeJalali,
    super.chassisNo,
    super.licensePlate,
    super.engineNumber,
    super.productYear,
    super.vehicleStatus,
    super.vehicleStatusTitle,
    super.installTypeDate,
    super.isTroubleShooter,
    super.imeiId,
    super.gradePatternCode,
    super.gradePatternName,
    super.gradeDetailsJson,
    super.gradeDetails,
    super.isActive,
    super.isDeleted,
  });

  factory AgencyVehicleModel.fromJson(Map<String, dynamic> json) {
    return AgencyVehicleModel(
      id: AgencyInfoJsonHelper.integer(json['id']),
      agencyInfoId: AgencyInfoJsonHelper.integer(json['agencyInfoId']),
      vehicleInfoId: AgencyInfoJsonHelper.integer(json['vehicleInfoId']),
      vehicleModelName: AgencyInfoJsonHelper.string(json['vehicleModelName']),
      vehicleModelTitle: AgencyInfoJsonHelper.string(json['vehicleModelTitle']),
      navganTypeTitle: AgencyInfoJsonHelper.string(json['navganTypeTitle']),
      imei: AgencyInfoJsonHelper.string(json['imei']),
      imeiSerial: AgencyInfoJsonHelper.string(json['imeiSerial']),
      navganTypeCode: AgencyInfoJsonHelper.string(json['navganTypeCode']),
      contractStartDate: AgencyInfoJsonHelper.string(json['contractStartDate']),
      contractStartDateJalali: AgencyInfoJsonHelper.string(json['contractStartDateJalali']),
      contractEndDate: AgencyInfoJsonHelper.string(json['contractEndDate']),
      contractEndDateJalali: AgencyInfoJsonHelper.string(json['contractEndDateJalali']),
      startBimeDate: AgencyInfoJsonHelper.string(json['startBimeDate']),
      startBimeDateJalali: AgencyInfoJsonHelper.string(json['startBimeDateJalali']),
      endBimeDate: AgencyInfoJsonHelper.string(json['endBimeDate']),
      endBimeDateJalali: AgencyInfoJsonHelper.string(json['endBimeDateJalali']),
      status: AgencyInfoJsonHelper.integer(json['status']),
      statusTitle: AgencyInfoJsonHelper.string(json['statusTitle']),
      contractCode: AgencyInfoJsonHelper.string(json['contractCode']),
      contractType: AgencyInfoJsonHelper.integer(json['contractType']),
      contractTypeTitle: AgencyInfoJsonHelper.string(json['contractTypeTitle']),
      labelAgencyCode: AgencyInfoJsonHelper.string(json['labelAgencyCode']),
      insertUserFullName: AgencyInfoJsonHelper.string(json['insertUserFullName']),
      updateUserFullName: AgencyInfoJsonHelper.string(json['updateUserFullName']),
      insertDateTime: AgencyInfoJsonHelper.string(json['insertDateTime']),
      insertDateTimeJalali: AgencyInfoJsonHelper.string(json['insertDateTimeJalali']),
      updateDateTime: AgencyInfoJsonHelper.string(json['updateDateTime']),
      updateDateTimeJalali: AgencyInfoJsonHelper.string(json['updateDateTimeJalali']),
      chassisNo: AgencyInfoJsonHelper.string(json['chassisNo']),
      licensePlate: AgencyInfoJsonHelper.string(json['licensePlate']),
      engineNumber: AgencyInfoJsonHelper.string(json['engineNumber']),
      productYear: AgencyInfoJsonHelper.string(json['productYear']),
      vehicleStatus: AgencyInfoJsonHelper.integer(json['vehicleStatus']),
      vehicleStatusTitle: AgencyInfoJsonHelper.string(json['vehicleStatusTitle']),
      installTypeDate: AgencyInfoJsonHelper.string(json['installTypeDate']),
      isTroubleShooter: AgencyInfoJsonHelper.boolean(json['isTroubleShooter']),
      imeiId: AgencyInfoJsonHelper.integer(json['imeiId']),
      gradePatternCode: AgencyInfoJsonHelper.integer(json['gradePatternCode']),
      gradePatternName: AgencyInfoJsonHelper.string(json['gradePatternName']),
      gradeDetailsJson: AgencyInfoJsonHelper.string(json['gradeDetailsJson']),
      gradeDetails: AgencyInfoJsonHelper.mapList(json['gradeDetails'])
          .map(AgencyVehicleGradeDetailModel.fromJson)
          .toList(),
      isActive: AgencyInfoJsonHelper.boolean(json['isActive']),
      isDeleted: AgencyInfoJsonHelper.boolean(json['isDeleted']),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'agencyInfoId': agencyInfoId,
      'vehicleInfoId': vehicleInfoId,
      'vehicleModelName': vehicleModelName,
      'vehicleModelTitle': vehicleModelTitle,
      'navganTypeTitle': navganTypeTitle,
      'imei': imei,
      'imeiSerial': imeiSerial,
      'navganTypeCode': navganTypeCode,
      'contractStartDate': contractStartDate,
      'contractStartDateJalali': contractStartDateJalali,
      'contractEndDate': contractEndDate,
      'contractEndDateJalali': contractEndDateJalali,
      'startBimeDate': startBimeDate,
      'startBimeDateJalali': startBimeDateJalali,
      'endBimeDate': endBimeDate,
      'endBimeDateJalali': endBimeDateJalali,
      'status': status,
      'statusTitle': statusTitle,
      'contractCode': contractCode,
      'contractType': contractType,
      'contractTypeTitle': contractTypeTitle,
      'labelAgencyCode': labelAgencyCode,
      'insertUserFullName': insertUserFullName,
      'updateUserFullName': updateUserFullName,
      'insertDateTime': insertDateTime,
      'insertDateTimeJalali': insertDateTimeJalali,
      'updateDateTime': updateDateTime,
      'updateDateTimeJalali': updateDateTimeJalali,
      'chassisNo': chassisNo,
      'licensePlate': licensePlate,
      'engineNumber': engineNumber,
      'productYear': productYear,
      'vehicleStatus': vehicleStatus,
      'vehicleStatusTitle': vehicleStatusTitle,
      'installTypeDate': installTypeDate,
      'isTroubleShooter': isTroubleShooter,
      'imeiId': imeiId,
      'gradePatternCode': gradePatternCode,
      'gradePatternName': gradePatternName,
      'gradeDetailsJson': gradeDetailsJson,
      'gradeDetails': gradeDetails?.map((item) => item.toModel().toJson()).toList(),
      'isActive': isActive,
      'isDeleted': isDeleted,
    };
  }
}
